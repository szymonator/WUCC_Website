                            <p class="wow fadeInUp" data-wow-delay="300ms"><b>Why should I use the training board?</b></p>
                            <ol class="wow fadeInUp mb-30" data-wow-delay="300ms" id="nlist">
                                <li>It is the best tool available in the climbing centre for power and contact strength</li>
                                <li>Training on the board is a very good way of training finger strength and core</li>
                                <li>Little feet are more like outdoor feet, and getting used to them will help you boost your grade outside, as well as make other indoor feet feel massive</li>
                                <li>You get to think more about movement by setting routes for yourself rather than only climbing routes set by other people</li>
                                <li>There are hundreds of problems on the board available on the Stokt app, many more than on the main wall</li>
                                <li>You will benefit from the psyche and desire to train hard of the other climbers who use the board, and train harder as a result</li>
                                <li>You can track your progress easily by comparing how easy a problem feels before a training period and how it feels after. Normal routes are reset every month, board problems are permanent</li>
