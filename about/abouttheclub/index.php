                            <p class="wow fadeInUp" data-wow-delay="100ms">For those newer to the sport, we hold tasters during both freshers and the first 2 weeks of term. These are free of charge and provide the perfect opportunity to try different types of climbing together with others new to the club. Since this is under the supervision of our exec it is also a great way to get to know us. Furthermore, for those unfamiliar with roped climbing we hold lessons during term 1 and term 2, ensuring all our members can safely master these skills and enjoy all our wonderful trips no matter of previous climbing experience. </p>
                            <p class="wow fadeInUp" data-wow-delay="200ms">If the idea of competing against other universities sounds appealing, this is something we do in abundance. Holding trials at the start of the year, most competitions are very relaxed ensuring the team remains fluid. Highlights of the previous academic year include finishing 2nd in the midlands and narrowly missing out on the podium against London universities. Throughout the year we also hold our own competitions which tend to be more informal, however an example of a more formal competition we host is the National Universities Lead and Speed Climbing Competition!</p>
                            <p class="wow fadeInUp" data-wow-delay="300ms">Finally, we hold weekly drinking and sober socials that cater for everyone. Whether you want to socialise on bar crawls or circle for POP! (the SU club), these events are a great way to meet others whether you drink or not. As far as sober socials these include watching films and hosting board game nights, providing a great opportunity to relax from your studies and meet fellow climbers. If any of this sounds exciting, you can learn more on our Instagram  (<a href="https://www.instagram.com/w_u_c_c/">@w_u_c_c</a>), <a href="https://linktr.ee/w_u_c_c">Whatsapp</a>, and our Facebook (<a href="https://www.facebook.com/groups/warwickuniversityclimbingclub">Warwick University Climbing Club</a>) where you can find further information about the things we get up to. We look forward to meeting everyone throughout the year and hope we can spread our passion for the sport which we love so much!</p>
