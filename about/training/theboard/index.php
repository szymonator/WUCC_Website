                        <p class="wow fadeInUp" data-wow-delay="300ms"><b>How do I know I'm ready?</b></p>
                        <ol class="wow fadeInUp mb-30" data-wow-delay="300ms" id="nlist">
                            <li>You are climbing V4 on the steeper walls in the main section</li>
                            <li>You are able to stand on small footholds</li>
                            <li>You are motivated to try hard and get strong</li>
                        </ol>
                        <p class="wow fadeInUp" data-wow-delay="300ms"><b>Grades:</b></p>
                        <ol class="wow fadeInUp mb-30" data-wow-delay="300ms" id="nlist">
                            <li>Make sure to change the grading system setting to the Font system instead of the default Hueco (V-grade) system. The Font system has greater resolution; for example, 6A and 6A+ in the Font system are both represented by V3 in the Heuco system. The Font system essentially allows you to discern whether a V3 graded problem is a hard or easy V3. The same applies for V4, V5 and V8</li>
                            <li>Font 4 (VB) represents the easiest grade climb possible on the board, it is not supposed to be the same difficulty as VBs in the rest of the centre. As such, a 6A/V3 on the board will feel harder than a V3 off the board, especially if you are still new to standing on the small red footholds and are still learning how to move on the board</li>
                            <li>After a climber has sent a problem they are invited to give it a grade. The grade displayed next to the problem is an average of these user grades</li>
                            <li>Height is a much bigger factor in the subjective difficulty of a climb on the board than it is a climb on the main wall. Some problems set by tall climbers will be impossible, or very difficult for short climbers, and vice versa. There is currently a lack of female and shorter climbers setting problems on the board. For those looking for such problems search for those by Niamh Gibson, Cait Clement and Gabby Han. For those looking for climbs for taller climbers search for Will Smith, Sylvan Chouhan and Sid Sherborne</li>
                        </ol>
                    </div>

                    <div class="col-12 col-lg-8 mb-30">
                        <p class="wow fadeInUp" data-wow-delay="300ms"><b>Climbing your first problem:</b></p>
                        <ol class="wow fadeInUp mb-30" data-wow-delay="300ms" id="nlist">
                            <li>Download the <a href="https://www.getstokt.com/?fbclid=IwAR3-pQENbCeUb9_22eh-zCcZYGFNBXuDh4lG560U9YManO6kLq8pNYxqilE" target="_blank">Stokd app</a></li>
                            <li>Make sure you are fully warmed up and have already climbed a few steeper problems on the main wall</li>
                            <li>Open the app. Next to the search bar is a slider icon. Click this and it will take you to the filters</li>
                            <li>Select a grade range you are comfortable with, 4 to 5 is a good starting place</li>
                            <li>Sort by either 'Easiest' or 'Most Repeats'</li>
                            <li>Pick a problem, check what the feet rules are for it, and try the moves. If you are unable to do it after 4 or 5 attempts, try another problem. You don't want to injure yourself by doing the same thing over and over. Come back to it next session</li>
                            <li>If the problems are too difficult, or you are struggling with the red feet, try making up your own problems using 'feet follow hands' or 'open feet' rules. Make sure to save these problems so other beginners can try them too!</li>
                        </ol>
                        <p class="wow fadeInUp" data-wow-delay="300ms"><b>What next?</b></p>
                        <ol class="wow fadeInUp mb-30" data-wow-delay="300ms" id="nlist">
                            <li>Work you way through the easier problems. If you try a problem but you can't do it yet (and it's not because you're too short for it), note it down and try it again in a few session's time. Use these problems to measure your progress</li>
                            <li>Try and do every problem on the app up to a certain grade</li>
                            <li>Have a flick through harder problems to see if any are your style and try them</li>
                            <li>Make up some problems to train your weaknesses. For me, that'd be locky moves on small crimps, for others it might be big power moves</li>
                            <li>Keep a list of problems which you want to do, and cross them off when you do them</li>
                            <li>When you're ready, graduate to the Ballroom Board, which is 45 degrees overhanging and with even harder grades</li>
                        </ol>
