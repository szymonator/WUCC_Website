                        <h3 class="wow fadeInUp" data-wow-delay="100ms">Giggleswick - 2016</h3>
                        <div class="line wow fadeInUp" data-wow-delay="200ms"></div>
                        <p class="wow fadeInUp" data-wow-delay="250ms" style="color:#A7A7A7">October 23, 2016 | Anthony Shaffu</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms"><b>Dates:</b> 21st October - 23rd October, 2016</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms"><b>Location:</b> Giggleswick, Yorkshire Dales</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">Only seventeen members of the club came on this trip, making it the smallest of the year. On Saturday, we woke up to a crisp and bright morning and headed to South Giggleswick. After walking up the approach on the side of a V-shaped valley, we got to the routes and started doing top-ropes on them.</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">For some of us, this was the first time we experienced climbing in the great outdoors. Everyone on this trip already knew how to lead - the Freshers Trip later on in the same term was for the newcomers to gain experience. After a while, some of us moved along to some adjacent routes round the corner. One route I did there stands out in my memory in particular - not for the route itself, but for the fact that I essentially learned how to lower off while at the top of the route. Those twenty minutes I had up there fiddling about with bits of gear while I had instuctions shouted at me from far below I have to say weren't far off terrifying (the quite fantastic view of the valley, perhaps, made up for it a little).</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">Nevertheless, I made it down safely, and thankfully have not had to experience anything quite as bad in any of the trips thereafter. Some would say this is an effective way to ensure that you don't forget how to lower off - I'd personally recommend practising plenty of times beforehand for minimal levels of stress. Anyway, after we had all done climbing for the day, we headed off to a pub not far away before making our way back to the bunkhouse. Dinner was lovingly prepared, eaten, and cleared away to make room for climbing games! This is an essential part of any trip: the box game; the bottle sling game; and the (other) sling game.</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">On the Sunday, we cleared the bunkhouse of our stuff, posed for photos outside, then headed to North Giggleswick for some marginally harder routes. As the evening approached, it was time to head back to university. Overall, this was a great weekend trip to kick the year off!</p>
