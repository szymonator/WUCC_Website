                        <p class="wow fadeInUp" data-wow-delay="300ms">The weather was mostly sunny and great for climbing although there were a couple of rainy days (as you can see from our not so sunny group photo). For those who wanted a break from climbing, the town of San Vito Lo Capo was around a 20min walk away (or 10mins if you managed to get yourself a ride) and had restaurants, shops and a sandy beach.</p>
