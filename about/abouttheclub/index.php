                            <p class="wow fadeInUp" data-wow-delay="500ms">We regularly organise outdoor trips across the UK visiting areas such as the Peak District and Wales. Catering for all different types and levels of climbing, we ensure these trips occur frequently to maximise opportunities for our members to experience the joy of climbing on real rock. In addition, every easter we travel to a world class European destination (previously Sicily, Siurana and El Chorro). These trips allow our members the freedom to explore many exceptional crags and are a fantastic way to meet like-minded people. </p>
