                        <h3 class="wow fadeInUp" data-wow-delay="100ms">El Chorro, Spain - 2018</h3>
                        <div class="line wow fadeInUp" data-wow-delay="200ms"></div>
                        <p class="wow fadeInUp" data-wow-delay="250ms" style="color:#A7A7A7">July 21, 2018 | Vickie Snow</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms"><b>Dates:</b> 19th March - 29th March, 2018</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms"><b>Location:</b> El Chorro, Andalucia, Spain</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">The 2018 tour to El Chorro was organised by the wonderful Tour Sec's Dec Rooney and Nidhi Unnithan. Here's a quick summary of the trip from Dec:</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">"The club flew to Malaga airport in order to travel to the beautiful region of El Chorro where we stayed for 11 nights in a selection of villas at Finca Rocabella. Each villa was equipped with its own pool and the accommodation had an on-site restaurant along with its own crag which featured a small selection of routes suitable for everyone to try.</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">The main climbing crags were a short 10-15 minute drive away and provided a range of grades from easy (3a ish) to hard (7c and above), so no matter what the ability, everyone got the chance to try some awesome climbing.</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">One of the highlights of the trip was the local Via Ferrata which was a series of metal rungs that followed the rock face. The Via Ferrata was equipped with two wire bridges that had to be traversed and a zipwire section. This was not for the faint hearted but was an enjoyable experience for those who tried it (safety equipment and experienced climbers were also essential). On rest days, the city of Ronda or Malaga were no more than an hours drive away and offered picture perfect scenery and unique experiences."</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">Check out the video from the Via Ferrata below (filmed by Dec, edited by me).</p>
