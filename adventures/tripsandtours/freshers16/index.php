                        <h3 class="wow fadeInUp" data-wow-delay="100ms">Freshers Trip - 2016</h3>
                        <div class="line wow fadeInUp" data-wow-delay="200ms"></div>
                        <p class="wow fadeInUp" data-wow-delay="250ms" style="color:#A7A7A7">November 13, 2016 | Sophie Davies</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms"><b>Dates:</b> 11th November - 13th November, 2016</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms"><b>Location:</b> Hope Valley, Peak District</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">The Fresher's Trip is usually the biggest trip of the year for our club. Its the first chance for our fresh meat to give outdoor climbing a go. It was a mildly damp yet incredibly enjoyable excursion.</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">We all headed to Horseshoe Quarry on the first day of out weekend trip. It is supposedly one of the best climbing destinations in the peaks, renown for fast drying rock appropriate in all sorts of weathers. We might agree with such, however the weather wasn't fantastic on the day that we were there at the quarry and it continued to drizzle as the exec set up top ropes. This meant that the rocks were very soggy for most of the day and a couple of routes in the top left corner were prone to muddy patches.</p>
                        <p class="wow fadeInUp" data-wow-delay="300ms">On Day 2 we went to Stanage Quarry here there was a little less protection from the elements as the rock was a little more raised however the weather was on our side that day. There was about a 20 minute approach time up a small hill. It didn't seem like much but our president had to jog up and down it twice because we forgot the trad rack! Stanage was a little more picturesque. Due to the fact that we could walk off the back of the routes we managed to get lots done that day because it was far easer to set up top ropes.</p>
